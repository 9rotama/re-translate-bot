export type LanguageCode = (typeof LANGUAGE_CODES)[number];

const supported: ReadonlySet<string> = new Set(LANGUAGE_CODES);
const isLanguageCode = (code: string): code is LanguageCode => supported.has(code);

// 大文字と小文字を区別しない（docs/interface.md の「言語コード」）。
// 区切りの空白の扱いは入力全体を分ける側の責務なので、ここでは前後の空白を許さない。
export function toLanguageCode(input: string): LanguageCode | undefined {
	const code = input.toLowerCase();
	return isLanguageCode(code) ? code : undefined;
}
